#!/usr/bin/env python3
"""Regenerate role-indexed sprites, palette tables and native bitmap fonts."""
from pathlib import Path
from itertools import groupby
import json
import re
from art import ART, Screen, build_palette, glyphs, tap, color

ROOT=Path(__file__).resolve().parents[1]
SOURCE_THEME_COUNT=52
SOURCE_THEME_INDICES={
    'Side A':0,
    'Side B':7,
    'Bootleg':14,
    'Blank Tape':26,
}
extras=['labelInk','activeInk','warnInk','greenInk']
roles=list(tap)+extras
assert len(roles)<127
role_index={name:i+1 for i,name in enumerate(roles)}
base=dict(tap,**{key:tap['bg'] if key=='labelInk' else tap['buttonInk'] for key in extras})
source_themes={0:('Side A',base)}
for line in (ROOT/'tools/palettes.txt').read_text().splitlines():
    name,raw=line.split('|')
    source_index=SOURCE_THEME_INDICES.get(name)
    if source_index is None:
        raise ValueError(f'Unknown source palette: {name}')
    if source_index in source_themes:
        raise ValueError(f'Duplicate source palette: {name}')
    source_themes[source_index]=(name,build_palette(raw))
for name,palette in json.loads((ROOT/'tools/imported-palettes.json').read_text()).items():
    if set(palette)!=set(roles) or any(not re.fullmatch(r'#[0-9a-fA-F]{6}', value)
                                       for value in palette.values()):
        raise ValueError(f'Invalid role palette: {name}')
    source_index=SOURCE_THEME_INDICES.get(name)
    if source_index is None:
        raise ValueError(f'Unknown source palette: {name}')
    if source_index in source_themes:
        raise ValueError(f'Duplicate source palette: {name}')
    source_themes[source_index]=(name,palette)
if set(source_themes)!=set(SOURCE_THEME_INDICES.values()):
    raise ValueError('Missing source palette')
theme_indices=json.loads((ROOT/'tools/embedded-theme-indices.json').read_text())
if (not isinstance(theme_indices,list) or not theme_indices or
    any(type(index) is not int or index<0 or index>=SOURCE_THEME_COUNT or index not in source_themes
        for index in theme_indices) or
    len(set(theme_indices))!=len(theme_indices)):
    raise ValueError('Invalid embedded theme indices')
themes=[source_themes[index] for index in theme_indices]
roles.append('cassetteScratch')
role_index['cassetteScratch']=len(roles)
for _,palette in themes:
    palette['cassetteScratch']=palette['shadow']
if len(themes)<4:
    raise ValueError('Four embedded themes are required for the cassette style set')
def upper(s):
    return re.sub(r'([a-z])([A-Z])',r'\1_\2',s).upper()
def cbytes(data,n=18):
    return '\n'.join('    '+', '.join(str(x) for x in data[i:i+n])+',' for i in range(0,len(data),n))
role_c={role:'HB_'+upper(role) for role in roles}
sprite_c={name:'HB_SPR_'+upper(name) for name,_,_ in ART}
header=['#ifndef HUMBUG_GENERATED_H','#define HUMBUG_GENERATED_H',
        'enum hb_role { HB_TRANSPARENT = 0,']
header += [f'    {role_c[r]} = {role_index[r]},' for r in roles]
header += ['    HB_ROLE_COUNT','};','enum hb_sprite_id {']
header += ['    '+sprite_c[n]+',' for n,_,_ in ART]
header += ['    HB_SPRITE_COUNT','};',f'#define HB_THEME_COUNT {len(themes)}',
           f'#define HB_THEME_SOURCE_COUNT {SOURCE_THEME_COUNT}',
           '#define HB_THEME_STYLE_SIDE_B 1',
           '#define HB_THEME_STYLE_BLANK_TAPE 2',
           '#define HB_THEME_STYLE_BOOTLEG 3',
           '#endif','']
(ROOT/'include/humbug_generated.h').write_text('\n'.join(header))

unique={role:(i,0,0) for role,i in role_index.items()}
source=['/* Generated by tools/build_assets.py */','#include "humbug_art.h"']
items=[]
total_rle=0
for name,(x,y,w,h),paint in ART:
    screen=Screen(unique)
    paint(screen)
    art=screen.im.crop((x,y,x+w,y+h))
    indices=[r for r,_,_ in art.get_flattened_data()]
    chunks=[]
    for idx,lookup in groupby(indices):
        n=sum(1 for _ in lookup)
        while n:
            size=min(255,n)
            chunks.extend((size,idx))
            n-=size
    assert sum(chunks[::2])==w*h
    assert all(0<=idx<len(roles)+1 for idx in indices)
    total_rle+=len(chunks)
    source.append(f'static const uint8_t sprite_{name}[] = {{\n'+cbytes(chunks)+'\n};')
    items.append(f'    [{sprite_c[name]}] = {{{x}, {y}, {w}, {h}, sprite_{name}, sizeof sprite_{name}}},')
    # The PNGs keep role indices. Entry 0 carries all transparent pixels.
    from PIL import Image
    png=Image.new('P',(w,h))
    png.putdata(indices)
    png.putpalette([0,0,0]+[v for role in roles for v in color(base[role])]+[0]*(3*(255-len(roles))))
    png.save(ROOT/f'assets/components/{name}.png', transparency=0)
source.extend(['const hb_sprite hb_sprites[HB_SPRITE_COUNT] = {',*items,'};'])
source.extend(['const uint8_t hb_glyphs[128][7] = {']+
              [f'    [{ord(ch)}] = {{'+', '.join(str(x) for x in bytes.fromhex(rows))+'},' for ch,rows in sorted(glyphs.items())]+['};'])
source.extend(['const char *const hb_theme_names[HB_THEME_COUNT] = {']+
              ['    '+json.dumps(name)+',' for name,_ in themes]+['};'])
source.extend(['const size_t hb_theme_source_indices[HB_THEME_COUNT] = {']+
              [f'    {index},' for index in theme_indices]+['};'])
source.append('const uint32_t hb_palettes[HB_THEME_COUNT][HB_ROLE_COUNT] = {')
for n,p in themes:
    source.append('    {0, '+', '.join('0x'+p[r].lstrip('#') for r in roles)+'},')
source.append('};')
source.extend(['const uint8_t hb_checkerboard_scrim[HB_THEME_COUNT] = {']+
              [f'    [{i}] = 1,' for i,(_,p) in enumerate(themes)
               if len({p[role].lower() for role in roles[:-1]})==4]+['};'])
(ROOT/'src/humbug_art.c').write_text('\n'.join(source)+'\n')
(ROOT/'assets/palettes.json').write_text(json.dumps({n:{r:p[r] for r in roles} for n,p in themes},indent=2)+'\n')
(ROOT/'assets/components.json').write_text(json.dumps({
    'transparentIndex':0,'roles':role_index,
    'components':{n:dict(zip(('x','y','width','height'),b)) for n,b,_ in ART},
    'compressedBytes':total_rle,
},indent=2)+'\n')

font_c=['/* Generated by tools/build_assets.py */','#include "humbug_fonts.h"',
        '#if __has_include("src/font/fmt_txt/lv_font_fmt_txt.h")',
        '#include "src/font/fmt_txt/lv_font_fmt_txt.h"',
        '#else','#include "src/font/lv_font_fmt_txt.h"','#endif']
# Each bitmap stores a digit or letter at integer scale on an opaque 1-bit grid.
# The native LVGL label fonts also alias ASCII lowercase to uppercase glyphs.
for scale in (1,2):
    name=f'humbug_pixel_{7*scale}'
    bdf=[f'STARTFONT 2.1',f'FONT -HUMBUG-Deck-Medium-R-Normal--{7*scale}-70-72-72-C-60-ISO10646-1',
         f'SIZE {7*scale} 72 72',f'FONTBOUNDINGBOX {5*scale} {7*scale} 0 0',
         f'STARTPROPERTIES 2',f'FONT_ASCENT {7*scale}','FONT_DESCENT 0','ENDPROPERTIES',f'CHARS 95']
    payload=[]; descriptors=['    {0},']
    for cp in range(32,127):
        ch=chr(cp)
        supported=ch.upper() if ch.upper() in glyphs else '?'
        glyph=bytes.fromhex(glyphs[supported])
        bits=[(row>>(4-x))&1 for row in glyph for _ in range(scale) for x in range(5) for _ in range(scale)]
        idx=len(payload)
        w,h=5*scale,7*scale
        encoded=[sum(bit<<(7-i) for i,bit in enumerate(bits[j:j+8])) for j in range(0,len(bits),8)]
        payload.extend(encoded)
        descriptors.append(f'    {{.bitmap_index={idx}, .adv_w={6*scale*16}, .box_w={w}, .box_h={h}, .ofs_x=0, .ofs_y=0}},')
        bdf += [f'STARTCHAR U+{cp:04X}',f'ENCODING {cp}','SWIDTH 857 0',f'DWIDTH {6*scale} 0',f'BBX {w} {h} 0 0','BITMAP']
        for y in range(h):
            row=bits[y*w:(y+1)*w]
            bytevalues=[sum(bit<<(7-i) for i,bit in enumerate(row[j:j+8])) for j in range(0,w,8)]
            bdf.append(''.join(f'{b:02X}' for b in bytevalues))
        bdf.append('ENDCHAR')
    (ROOT/f'assets/fonts/{name}.bdf').write_text('\n'.join(bdf+['ENDFONT'])+'\n')
    font_c += [f'static const uint8_t bitmap_{scale}[] = {{',cbytes(payload),'};',
               f'static const lv_font_fmt_txt_glyph_dsc_t glyph_{scale}[] = {{',*descriptors,'};',
               f'static const lv_font_fmt_txt_cmap_t cmap_{scale}[] = {{',
               '    {.range_start=32, .range_length=95, .glyph_id_start=1, .type=LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},','};',
               f'static const lv_font_fmt_txt_dsc_t desc_{scale} = {{',
               f'    .glyph_bitmap=bitmap_{scale}, .glyph_dsc=glyph_{scale}, .cmaps=cmap_{scale},',
               '    .cmap_num=1, .bpp=1, .bitmap_format=0,','};',
               f'const lv_font_t {name} = {{',
               '    .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,',
               f'    .line_height={7*scale}, .base_line=0, .dsc=&desc_{scale},','};']
(ROOT/'src/humbug_fonts.c').write_text('\n'.join(font_c)+'\n')
print(f'{len(ART)} sprites, {total_rle} compressed bytes, {len(themes)} palettes and two native fonts')
